# Independence-from-B192 check for the E7 Z2^6 x Z12 kernel.
import json, numpy as np, itertools
from fractions import Fraction
from collections import Counter
d=json.load(open('../../../reports/round4-E7-run012/full.cont3.frac.json')); P=np.array(d['P']); q=d['q']
a=np.fromfile('g/2_6_1_0_r12.bin',dtype=np.int32); n=int(a[0]); orb=a[2:2+n]; D=a[2+n:].reshape(n,n)
p=P[orb].astype(np.int64)  # p[g], g = x*12+t
X=np.arange(n)//12; T=np.arange(n)%12
def add(g,h): return ((X[g]^X[h])*12 + (T[g]+T[h])%12)
# period subgroup
per=[h for h in range(n) if np.array_equal(p[add(np.arange(n),h)], p)]
print('translation-period subgroup order', len(per), per[:8])
# levels
print('distinct levels', len(set(p.tolist())), 'count 0:', int((p==0).sum()), 'count q:', int((p==q).sum()))
# Z4 average (H = {0,3,6,9} in Z12)
H=[0,3,6,9]
pa=sum(p[add(np.arange(n),h)] for h in H)  # 4*avg
# quotient on Z2^6 x Z3: coset rep x*12 + t with t in {0,1,2}? coset of t: t mod 3
reps=[x*12+t for x in range(64) for t in range(3)]
pq=np.array([pa[r] for r in reps])  # numerators over 4q
lv=Counter((Fraction(int(v),4*q)) for v in pq)
print('Z4-quotient: distinct levels', len(lv), 'fraction at 0/1', sum(c for k,c in lv.items() if k in (0,1))/192)
# density of quotient kernel (192): t = sum over g1,g2,g3 of prod, translated
m=192; xs=np.array([r//12 for r in reps]); ts=np.array([r%12 for r in reps])
Wf=np.zeros((m,m))
for i in range(m):
    for j in range(m):
        g=((xs[i]^xs[j])*12 + (ts[j]-ts[i])%12)
        Wf[i,j]=pa[g]/(4*q)
for M in (Wf,):
    pass
def t4(M):
    s=0.0
    for b in range(m):
        v=M[0]*M[b]; s+=M[0,b]*(v@M@v)
    return s/m**3
B=1-Wf
print('Z4-quotient density', t4(Wf)+t4(B), 'symmetric', np.allclose(Wf,Wf.T))
# largest variation inside Z4 cosets
var=np.array([max(p[add(g,h)] for h in H)-min(p[add(g,h)] for h in H) for g in range(n)])
print('fraction of elements whose Z4 coset is non-constant', np.mean(var>0))
# other order-4 subgroups: Z2^2 inside F64 x {0,6}? test all subgroups generated by (x1,t1),(x2,t2) with order-2 elements
inv=[g for g in range(n) if add(g,g)==0 and g!=0]
best=None
for g1,g2 in itertools.combinations(inv,2):
    Hs=[0,g1,g2,add(g1,g2)]
    nc=np.mean([len(set(p[add(g,h)] for h in Hs))>1 for g in range(0,n,1)])
    if best is None or nc<best[0]: best=(nc,Hs)
print('best Z2^2 subgroup: fraction non-constant cosets', best)
np.save('../../../reports/round4-E7-run012/z4_quotient.npy', Wf)
# --- quotient by best Z2^2 subgroup
Hs=[int(h) for h in best[1]]
print('levels of kernel (numerators/q):', sorted(Counter(p.tolist()).items()))
coset_id=-np.ones(n,dtype=int); reps2=[]
for g in range(n):
    if coset_id[g]<0:
        for h in Hs: coset_id[add(g,h)]=len(reps2)
        reps2.append(g)
m=len(reps2); pa2=sum(p[add(np.arange(n),h)] for h in Hs)
W2=np.array([[pa2[add(reps2[j], reps2[i])] if False else 0 for j in range(m)] for i in range(m)],dtype=float)
# difference g_j - g_i : in char-2 x-part xor, t part (tj - ti)
for i in range(m):
    gi=reps2[i]
    for j in range(m):
        gj=reps2[j]; g=((X[gi]^X[gj])*12 + (T[gj]-T[gi])%12)
        W2[i,j]=pa2[g]/(4*q)
print('Z2^2-quotient order', m, 'density', t4(W2)+t4(1-W2))
print('Z2^2-quotient levels', sorted(Counter(np.round(W2[0],6).tolist()).items()))
